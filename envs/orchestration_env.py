"""
Closed-Loop Tool-Use Orchestration Environment.
Models multi-step agent-environment interaction:
- Unobserved state space S
- Discrete action space A_env and continuous grounding mapping g(a_text) -> a_env
- Grounding gap Delta_g(t)
- Observation transition T(s_{t+1}, o_t | s_t, a_t)
- Cascading goal evaluation across horizons T
"""

import torch
import numpy as np
from typing import Tuple, Dict, Any, Optional

class OrchestrationEnvironment:
    """
    Simulates a high-dimensional multi-step tool-orchestration task
    (e.g., API workflow, database transformation, multi-stage reasoning).
    """
    def __init__(self, state_dim: int = 128, max_horizon: int = 100, nominal_grounding_gap: float = 0.05, seed: int = 42):
        self.state_dim = state_dim
        self.max_horizon = max_horizon
        self.nominal_grounding_gap = nominal_grounding_gap
        self.seed = seed
        self.reset()

    def reset(self, seed: Optional[int] = None) -> torch.Tensor:
        if seed is not None:
            torch.manual_seed(seed)
            np.random.seed(seed)
            
        self.t = 0
        # Latent true environment state
        self.env_state = torch.randn(self.state_dim)
        self.env_state = self.env_state / torch.norm(self.env_state)
        
        # Target goal manifold: reachable target state
        perturb = torch.randn(self.state_dim) * 0.25
        self.goal_state = self.env_state + perturb
        self.goal_state = self.goal_state / torch.norm(self.goal_state)
        
        # Initial observation
        obs = self._generate_observation()
        return obs

    def _generate_observation(self) -> torch.Tensor:
        """Generates observation vector o_t with task guidance and sensor noise."""
        noise = torch.randn(self.state_dim) * 0.02
        # Observation provides feedback on current error relative to goal
        obs = 0.7 * self.goal_state + 0.3 * self.env_state + noise
        return obs / torch.norm(obs)

    def step(self, action_vector: torch.Tensor, gap_type: str = "nominal") -> Tuple[torch.Tensor, float, bool, Dict[str, Any]]:
        """
        Executes action in environment.
        Args:
            action_vector: [d] linguistic action embedding generated by agent
            gap_type: 'nominal', 'drift', 'pareto_heavy', or 'adversarial'
        Returns:
            observation: [d] new observation vector o_{t+1}
            reward: float fidelity score
            done: boolean indicator
            info: metadata (grounding gap, true state distance, success indicator)
        """
        self.t += 1
        
        # Compute grounding gap Delta_g(t) based on noise model
        if gap_type == "nominal":
            grounding_gap = self.nominal_grounding_gap + np.random.normal(0, 0.005)
        elif gap_type == "drift":
            grounding_gap = self.nominal_grounding_gap + 0.001 * (self.t ** 1.1) + np.random.normal(0, 0.005)
        elif gap_type == "pareto_heavy":
            # Heavy-tailed bursts
            pareto_shock = (np.random.pareto(a=2.5) - 1.0) * 0.03
            grounding_gap = self.nominal_grounding_gap + max(0.0, pareto_shock)
        elif gap_type == "adversarial":
            grounding_gap = self.nominal_grounding_gap * (1.5 + 0.5 * np.sin(self.t / 4.0))
        else:
            grounding_gap = self.nominal_grounding_gap
            
        grounding_gap = float(max(0.001, grounding_gap))
        
        # Normalize action direction
        act_norm = torch.norm(action_vector).item()
        if act_norm > 0:
            a_dir = action_vector / act_norm
        else:
            a_dir = action_vector
            
        # Grounding mapping: g(a_text) = a_env + Delta_g * e_perturb
        perturbation = torch.randn(self.state_dim)
        perturbation = perturbation / torch.norm(perturbation)
        a_env = a_dir + grounding_gap * perturbation
        
        # Environment state transition: latent dynamics driven by action
        self.env_state = 0.88 * self.env_state + 0.12 * a_env + torch.randn(self.state_dim) * 0.008
        self.env_state = self.env_state / torch.norm(self.env_state)
        
        # Distance to target goal
        dist_to_goal = float(torch.norm(self.env_state - self.goal_state).item())
        reward = -dist_to_goal
        
        # Task success condition: agent maintains state alignment within threshold
        is_success = (dist_to_goal < 0.85)
        is_diverged = (act_norm > 4.5) or (dist_to_goal > 1.75)
        
        done = (self.t >= self.max_horizon) or is_diverged
        
        obs = self._generate_observation()
        info = {
            "grounding_gap": grounding_gap,
            "dist_to_goal": dist_to_goal,
            "is_success": is_success,
            "is_diverged": is_diverged,
            "step": self.t
        }
        return obs, reward, done, info
